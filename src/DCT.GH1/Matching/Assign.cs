using System;
using DigitalCircularityToolkit.Framework;
using Grasshopper.Kernel;
using DigitalCircularityToolkit.Numerics;
using System.Collections.Generic;
using DigitalCircularityToolkit.Distance;

namespace DigitalCircularityToolkit.Matching
{
    /// <summary>Assign supply to demand at the lowest total cost (linear assignment on a cost matrix)</summary>
    public class Assign : DctComponent
    {
        // Last result, kept for AutoRun = false (COMPONENT_SPEC §4.6).
        private AssignmentResult _result;

        public Assign()
          : base("Assign", "Assign", "Assign supply to demand at the lowest total cost (linear assignment on a cost matrix)", "Matching")
        {
        }

        protected override void RegisterInputParams(GH_InputParamManager pManager)
        {
            pManager.AddParameter(new Param_CostMatrix(), "CostMatrix", "CM", "Cost matrix from a cost component (rows = demand, columns = supply)", GH_ParamAccess.item);
            pManager.AddBooleanParameter("AutoRun", "Auto", "True: solve whenever the input changes. False: keep the last result until set to true again (e.g. wire a button for large problems)", GH_ParamAccess.item, true);
            pManager[1].Optional = true;
        }

        protected override void RegisterOutputParams(GH_OutputParamManager pManager)
        {
            pManager.AddIntegerParameter("Assignment", "A", "A[i] = j: supply item j serves demand item i; -1 = no supply for demand i", GH_ParamAccess.list);
            pManager.AddNumberParameter("Cost", "C", "Total cost of the assigned pairs", GH_ParamAccess.item);
            pManager.AddIntegerParameter("Unassigned", "U", "Indices of the demand items with no supply", GH_ParamAccess.list);
        }

        protected override void SolveInstance(IGH_DataAccess DA)
        {
            CostMatrix matrix = null;
            bool auto = true;
            if (!DA.GetData(0, ref matrix) || matrix == null) return;
            DA.GetData(1, ref auto);

            if (auto)
            {
                _result = LinearAssignment.Solve(matrix);
            }
            else if (_result == null)
            {
                AddRuntimeMessage(GH_RuntimeMessageLevel.Remark, "AutoRun is false and nothing has been solved yet. Set AutoRun to true (e.g. press a button) to solve.");
                return;
            }

            var unassigned = new List<int>();
            for (int i = 0; i < _result.Assignment.Length; i++)
                if (_result.Assignment[i] < 0) unassigned.Add(i);
            if (unassigned.Count > 0)
                AddRuntimeMessage(GH_RuntimeMessageLevel.Remark, string.Format(
                    "{0} demand item(s) have no supply (Assignment -1): fewer supply items than demand, or only forbidden pairs left", unassigned.Count));
            if (auto && _result.UsedMonotonePath)
                AddRuntimeMessage(GH_RuntimeMessageLevel.Remark, "One feature with a convex cost: solved by sorted (monotone) matching");

            DA.SetDataList(0, _result.Assignment);
            DA.SetData(1, _result.Cost);
            DA.SetDataList(2, unassigned);
        }

        // Generated by scripts/new-component.sh. Never change after release.
        public override Guid ComponentGuid => new Guid("9616DAE5-2F41-47E6-8515-0FB0F819939C");

        public override GH_Exposure Exposure => GH_Exposure.primary;
    }
}

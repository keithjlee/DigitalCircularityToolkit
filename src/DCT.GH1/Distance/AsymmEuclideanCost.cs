using System;
using DigitalCircularityToolkit.Framework;
using Grasshopper.Kernel;
using DigitalCircularityToolkit.Numerics;

namespace DigitalCircularityToolkit.Distance
{
    /// <summary>Cost matrix of asymmetric Euclidean distances: one power when the supply covers the demand, another (or forbidden) when it falls short</summary>
    public class AsymmEuclideanCost : DctComponent
    {
        public AsymmEuclideanCost()
          : base("AsymmEuclideanCost", "CostAsym", "Cost matrix of asymmetric Euclidean distances: one power when the supply covers the demand, another (or forbidden) when it falls short", "Distance")
        {
        }

        protected override void RegisterInputParams(GH_InputParamManager pManager)
        {
            pManager.AddNumberParameter("Demand", "FVdemand", "Demand feature vectors: one branch per demand item", GH_ParamAccess.tree);
            pManager.AddNumberParameter("Supply", "FVsupply", "Supply feature vectors: one branch per supply item, same length as the demand vectors", GH_ParamAccess.tree);
            pManager.AddNumberParameter("Power1", "p", "Cost = distance^p when the supply is at least the demand in every feature (> 0)", GH_ParamAccess.item, 1.0);
            pManager.AddNumberParameter("Power2", "q", "Cost = distance^q when the supply is smaller in any feature (> 0). With distances below 1, a larger power gives a smaller cost", GH_ParamAccess.item, 2.0);
            pManager.AddBooleanParameter("ForbidShortfall", "Forbid", "True: a supply smaller than the demand in any feature can never be assigned (cost ∞), and Power2 is ignored", GH_ParamAccess.item, false);
            pManager[2].Optional = true;
            pManager[3].Optional = true;
            pManager[4].Optional = true;
        }

        protected override void RegisterOutputParams(GH_OutputParamManager pManager)
        {
            pManager.AddParameter(new Param_CostMatrix(), "CostMatrix", "CM", "Cost of serving demand i (row) with supply j (column), in double precision", GH_ParamAccess.item);
        }

        protected override void SolveInstance(IGH_DataAccess DA)
        {
            if (!CostInputs.Read(DA, 0, 1, out double[][] demand, out double[][] supply, out string error))
            {
                if (error != null) AddRuntimeMessage(GH_RuntimeMessageLevel.Error, error);
                return;
            }
            double p = 1, q = 2;
            bool forbid = false;
            DA.GetData(2, ref p);
            DA.GetData(3, ref q);
            DA.GetData(4, ref forbid);
            string bad = CostInputs.CheckPower("Power1", p) ?? (forbid ? null : CostInputs.CheckPower("Power2", q));
            if (bad != null)
            {
                AddRuntimeMessage(GH_RuntimeMessageLevel.Error, bad);
                return;
            }
            if (!forbid && q <= p)
                AddRuntimeMessage(GH_RuntimeMessageLevel.Remark, "Power2 <= Power1: a supply that falls short is not penalized more than one that covers the demand");

            DA.SetData(0, new GH_CostMatrix(CostFunctions.AsymmetricEuclideanMatrix(demand, supply, p, q, forbid)));
        }

        // Generated by scripts/new-component.sh. Never change after release.
        public override Guid ComponentGuid => new Guid("FD022099-ADA8-4C3E-B854-2DBA3849DCEF");

        public override GH_Exposure Exposure => GH_Exposure.primary;
    }
}

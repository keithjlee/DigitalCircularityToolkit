using System;
using DigitalCircularityToolkit.Framework;
using Grasshopper.Kernel;
using DigitalCircularityToolkit.Numerics;
using Grasshopper.Kernel.Data;
using Grasshopper.Kernel.Types;

namespace DigitalCircularityToolkit.Distance
{
    /// <summary>Cost matrix as a tree of numbers: one branch per demand, one item per supply</summary>
    public class CostMatrixToTree : DctComponent
    {
        public CostMatrixToTree()
          : base("CostMatrixToTree", "CM2Tree", "Cost matrix as a tree of numbers: one branch per demand, one item per supply", "Distance")
        {
        }

        protected override void RegisterInputParams(GH_InputParamManager pManager)
        {
            pManager.AddParameter(new Param_CostMatrix(), "CostMatrix", "CM", "Cost matrix to inspect", GH_ParamAccess.item);
        }

        protected override void RegisterOutputParams(GH_OutputParamManager pManager)
        {
            pManager.AddNumberParameter("Costs", "C", "One branch {i} per demand item, one cost per supply item (∞ = forbidden)", GH_ParamAccess.tree);
        }

        protected override void SolveInstance(IGH_DataAccess DA)
        {
            CostMatrix matrix = null;
            if (!DA.GetData(0, ref matrix) || matrix == null) return;

            var tree = new GH_Structure<GH_Number>();
            for (int i = 0; i < matrix.Rows; i++)
            {
                ReadOnlySpan<double> row = matrix.Row(i);
                var branch = new GH_Number[row.Length];
                for (int j = 0; j < branch.Length; j++) branch[j] = new GH_Number(row[j]);
                tree.AppendRange(branch, new GH_Path(i));
            }
            DA.SetDataTree(0, tree);
        }

        // Generated by scripts/new-component.sh. Never change after release.
        public override Guid ComponentGuid => new Guid("B8D68AAB-A674-4218-A9F2-12612C6A349B");

        public override GH_Exposure Exposure => GH_Exposure.secondary;
    }
}

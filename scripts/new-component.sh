#!/usr/bin/env bash
# Scaffold a new Grasshopper component: C# file + fresh GUID + placeholder vector icon.
#
#   scripts/new-component.sh <ClassName> <Subcategory> [options]
#
#   Subcategory: Objects | Sets | Characterization | Distance | Matching | Utilities
#   Options:
#     --kind component|modifier   template (default: component; modifier = object in -> same-type object out)
#     --name "Display Name"       shown name, " (DCT)" is appended (default: ClassName)
#     --nick Nick                 nickname (default: ClassName)
#     --desc "Description"        (default: TODO)
#     --exposure primary|secondary|tertiary|...   (default: primary)
#
# Creates  <Subcategory>/<ClassName>.cs          (namespace DigitalCircularityToolkit.<Subcategory>)
#          Icons/<ClassName>.svg                 (placeholder with initials; replace with the real drawing)
# The next `dotnet build` renders Resources/Icons/<ClassName>.png and embeds it; DctComponent picks it up by name.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
usage() { sed -n '2,18p' "$0" | sed 's/^# \{0,1\}//'; exit 1; }
[[ $# -lt 2 ]] && usage

CLASS="$1"; SUBCAT="$2"; shift 2
KIND=component; NAME="$CLASS"; NICK="$CLASS"; DESC="TODO: describe $CLASS"; EXPOSURE=primary
while [[ $# -gt 0 ]]; do
  case "$1" in
    --kind) KIND="$2"; shift 2 ;;
    --name) NAME="$2"; shift 2 ;;
    --nick) NICK="$2"; shift 2 ;;
    --desc) DESC="$2"; shift 2 ;;
    --exposure) EXPOSURE="$2"; shift 2 ;;
    *) usage ;;
  esac
done

[[ "$CLASS" =~ ^[A-Z][A-Za-z0-9_]*$ ]] || { echo "ClassName must be a PascalCase C# identifier" >&2; exit 1; }
case "$SUBCAT" in Objects|Sets|Characterization|Distance|Matching|Utilities) ;; *)
  echo "Unknown subcategory '$SUBCAT' (Objects|Sets|Characterization|Distance|Matching|Utilities)" >&2; exit 1 ;; esac
TEMPLATE="$ROOT/scripts/templates/$KIND.cs.tmpl"
[[ -f "$TEMPLATE" ]] || { echo "No template for kind '$KIND'" >&2; exit 1; }

CS="$ROOT/$SUBCAT/$CLASS.cs"
SVG="$ROOT/Icons/$CLASS.svg"
[[ -e "$CS" ]] && { echo "$CS already exists" >&2; exit 1; }
if grep -rqs --include='*.cs' "class $CLASS\b" "$ROOT" --exclude-dir=bin --exclude-dir=obj --exclude-dir=tools; then
  echo "A class named $CLASS already exists" >&2; exit 1
fi

GUID="$(uuidgen | tr '[:lower:]' '[:upper:]')"
# escape for a C# string literal (\ and "), then for a sed replacement (\ & |)
esc() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' | sed -e 's/[\\&|]/\\&/g'; }
sed -e "s|__NAMESPACE__|DigitalCircularityToolkit.$SUBCAT|g" \
    -e "s|__CLASS__|$CLASS|g" \
    -e "s|__NAME__|$(esc "$NAME")|g" \
    -e "s|__NICK__|$(esc "$NICK")|g" \
    -e "s|__DESC__|$(esc "$DESC")|g" \
    -e "s|__SUBCAT__|$SUBCAT|g" \
    -e "s|__GUID__|$GUID|g" \
    -e "s|__EXPOSURE__|$EXPOSURE|g" \
    "$TEMPLATE" > "$CS"

# Placeholder icon in the style of the existing set: grey frame, light fill, blue initials.
INITIALS="$(printf '%s' "$CLASS" | sed 's/[^A-Z]//g' | cut -c1-2)"
[[ -z "$INITIALS" ]] && INITIALS="$(printf '%s' "$CLASS" | cut -c1-2)"
mkdir -p "$ROOT/Icons"
if [[ ! -e "$SVG" ]]; then
  cat > "$SVG" <<EOF
<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">
  <!-- PLACEHOLDER generated by scripts/new-component.sh: replace with the real icon (24x24 artboard). -->
  <rect x="1" y="1" width="22" height="22" fill="#ffffff" stroke="#b3b3b3" stroke-width="2"/>
  <text x="12" y="16.5" font-family="Helvetica, Arial, sans-serif" font-size="11" font-weight="bold"
        text-anchor="middle" fill="#2559f5">$INITIALS</text>
</svg>
EOF
fi

echo "created  ${CS#$ROOT/}  (GUID $GUID)"
echo "created  ${SVG#$ROOT/}  (placeholder icon)"
echo "next:    edit the component, draw the icon, then scripts/rhino-dev.sh"
